# 语义索引 Agent 发现（governance/agent_discovery/）
#
# 职责：基于语义索引的 Agent 能力发现——关键词倒排索引 + 可选向量索引 +
#       RRF 混合检索 + RBAC 过滤 + 相关度阈值过滤 + 描述来源三态管理。
# 设计意图（对应偏差修正 T192-T203 / design 2.1.3.3）：
#   - 关键词倒排索引：纯标准库实现，无外部依赖
#   - 向量索引后端可选（延迟导入，空配置即纯关键词降级）
#   - 混合检索采用 RRF（Reciprocal Rank Fusion）融合两路排序
#   - 结果按 RBAC 权限过滤，仅返回调用方可见 Agent
#   - 描述来源三态：PROVIDER / LLM_GENERATED / MANUAL_REVISION
#   - agent_discovery_enabled=False 时路由不注册
